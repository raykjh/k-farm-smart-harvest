test('staff consultation saves test draft but never authorizes farming',async({page})=>{
 await page.goto('/register');
 await page.getByLabel('이름',{exact:true}).fill('테스트 농부');
 await page.getByLabel('생년월일').fill('1960-01-01');
 await page.getByLabel('연락처',{exact:true}).fill('000-0000-0000');
 await page.getByRole('button',{name:'다음',exact:true}).click();
 await page.getByRole('button',{name:'농지 추가'}).click();
 await page.getByLabel('지번 주소').fill('테스트 농지 1');
 await page.getByLabel('작업 면적').fill('3000');
 await expect(page.getByLabel('소유·이용관계')).toHaveValue('owned');
 await page.getByLabel('이용 권한 확인자료').selectOption('ownership');
 await expect(page.getByText('이용 권한 확인: 보류.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'다음',exact:true}).click();
 await page.locator('input[type="radio"][value="rice"]').check();
 await expect(page.locator('.crop-choice')).toHaveCount(3);
 await expect(page.locator('.crop-choice').first()).toContainText('1,542–1,590 kg');
 await page.locator('input[type="radio"][value="delegated"]').check();
 await expect(page.locator('input[type="radio"][value="joint"]')).not.toBeChecked();
 await page.screenshot({path:'test-results/registration-crops.png',fullPage:true});
 await page.getByRole('button',{name:'다음',exact:true}).click();
 await page.getByRole('button',{name:'농지 목록에 저장 · 권한 보류'}).click();
 await expect(page.getByRole('status')).toContainText('PNU');
 await page.getByRole('button',{name:'임시 저장',exact:true}).click();
 await page.reload();await page.getByRole('button',{name:'초안 불러오기'}).click();
 await expect(page.getByLabel('이름',{exact:true})).toHaveValue('테스트 농부');
 await page.getByLabel('언어 / Language').selectOption('en');
 await expect(page.getByRole('heading',{name:'Field registration form'})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/registration-mobile.png',fullPage:true});
});
