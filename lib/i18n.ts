 if(/^\d+건 변경계획 일괄 승인$/.test(key))return `Approve all ${key.match(/\d+/)![0]} changes`;
 if(/^\d+월 \d+일 \d{2}:\d{2}$/.test(key))return key.replace(/^(\d+)월 (\d+)일 /,(_,m,d)=>`${['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][Number(m)-1]} ${d}, `);
